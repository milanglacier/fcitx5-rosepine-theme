"""Generate the fcitx5 theme.conf files from the Rosé Pine Squirrel schemes.

Squirrel writes colors as 0xAABBGGRR (or 0xBBGGRR when opaque), so the
channels must be reversed. The schemes also set color_space: display_p3, so
the values are converted from Display P3 to sRGB for fcitx5, which expects
#RRGGBBAA.

Run from the repository root: python3 scripts/generate.py
"""

