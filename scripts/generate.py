# Linear Display P3 to linear sRGB.
P3_TO_SRGB = (
    (1.2249401, -0.2249404, 0.0),
    (-0.0420569, 1.0420571, 0.0),
    (-0.0196376, -0.0786361, 1.0982735),
)


def decode(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def encode(c):
    c = min(max(c, 0.0), 1.0)
    return c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def color(value):
    """Convert a Squirrel 0xAABBGGRR Display P3 value to fcitx5 #RRGGBBAA."""
    alpha = (value >> 24) & 0xFF if value > 0xFFFFFF else 0xFF
    p3 = [decode(((value >> shift) & 0xFF) / 255) for shift in (0, 8, 16)]
    srgb = [encode(sum(m * c for m, c in zip(row, p3))) for row in P3_TO_SRGB]
    rgb = "".join(f"{round(c * 255):02x}" for c in srgb)
    return f"#{rgb}" if alpha == 0xFF else f"#{rgb}{alpha:02x}"


